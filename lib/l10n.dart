const supportedLanguages = ['ru', 'en'];

/// Язык берём из Localizations: MaterialApp уже учёл выбор в настройках.
String langOf(BuildContext context) {
  final l = Localizations.maybeLocaleOf(context)?.languageCode ?? 'ru';
  return supportedLanguages.contains(l) ? l : 'en';
}

extension L10nX on BuildContext {
  String t(String key, [Map<String, String>? args]) {
    final lang = langOf(this);
    var s = strings[lang]?[key] ?? strings['ru']![key] ?? key;
    args?.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }
}

String capitalize(String s) =>
    s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);

String formatMonthYear(BuildContext context, DateTime d) {
  final lang = langOf(context);
  // В русском нужен именительный падеж: «октябрь», а не «октября».
  return DateFormat(lang == 'ru' ? 'LLLL y' : 'MMMM y', lang).format(d);
}

String formatDate(BuildContext context, DateTime d) =>
    DateFormat('d MMMM', langOf(context)).format(d);

String formatDateFull(BuildContext context, DateTime d) =>
    DateFormat('d MMMM y, EEEE', langOf(context)).format(d);

List<String> weekdayShort(BuildContext context) => langOf(context) == 'ru'
    ? const ['Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб', 'Вс']
    : const ['Mo', 'Tu', 'We', 'Th', 'Fr', 'Sa', 'Su'];

/// Русское склонение: 1 подписчик, 2 подписчика, 5 подписчиков.
String plural(BuildContext context, int n, String key) {
  final lang = langOf(context);
  if (lang != 'ru') return context.t(n == 1 ? '${key}_one' : '${key}_many');
  final m10 = n % 10, m100 = n % 100;
  final form = m10 == 1 && m100 != 11
      ? 'one'
      : (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14))
      ? 'few'
      : 'many';
  return context.t('${key}_$form');
}

